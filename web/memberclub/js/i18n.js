export function bindSettings(root = document) {
  root.querySelectorAll(".set-dd").forEach(dd => {
    if (dd.dataset.bound) return;
    dd.dataset.bound = "1";
    const btn = dd.querySelector(".set-btn"), panel = dd.querySelector(".set-panel");
    btn.addEventListener("click", e => {
      e.stopPropagation();
      const bp = document.getElementById("bellPanel");
      if (bp) bp.classList.add("hidden");   // 和铃铛不同时打开
      panel.classList.toggle("hidden");
      if (!panel.classList.contains("hidden")) {
        fitSetRows(panel);
        // 字体档案还在下载时量到的宽度不准：下载完再量一次
        if (document.fonts && document.fonts.status !== "loaded") document.fonts.ready.then(() => { if (!panel.classList.contains("hidden")) fitSetRows(panel); });
      }
    });
    panel.addEventListener("click", e => {
      e.stopPropagation();
      const tb = e.target.closest("[data-settheme]");
      if (tb) {
        setTheme(tb.dataset.settheme);
        panel.querySelectorAll("[data-settheme]").forEach(b => b.classList.toggle("on", b === tb));
        return;
      }
      const fb = e.target.closest("[data-setfs]");
      if (fb) {
        setFontSize(fb.dataset.setfs);
        panel.querySelectorAll("[data-setfs]").forEach(b => b.classList.toggle("on", b === fb));
        fitSetRows(panel);   // 字变大后，放不下的排改成只显示图示
        return;
      }
      const sb = e.target.closest("[data-setsound]");
      if (sb) {
        setSound(sb.dataset.setsound === "on");
        panel.querySelectorAll("[data-setsound]").forEach(b => b.classList.toggle("on", b === sb));
        if (sb.dataset.setsound === "on") playChime();   // 打开时响一声给会员听
        return;
      }
      const lb = e.target.closest("[data-setlang]");
      if (lb && lb.dataset.setlang !== lang) setLang(lb.dataset.setlang);
    });
    document.addEventListener("click", e => { if (!dd.contains(e.target)) panel.classList.add("hidden"); });
  });
}

// 语言按钮：平常只显示目前语言，点了才展开选单
export function bindLangSwitch(root = document) {
  root.querySelectorAll(".lang-dd").forEach(dd => {
    const btn = dd.querySelector(".lang-btn");
    const menu = dd.querySelector(".lang-menu");
    btn.addEventListener("click", e => { e.stopPropagation(); menu.classList.toggle("hidden"); });
    menu.querySelectorAll("[data-setlang]").forEach(b => {
      b.addEventListener("click", () => {
        menu.classList.add("hidden");
        if (b.dataset.setlang !== lang) setLang(b.dataset.setlang);
      });
    });
    document.addEventListener("click", e => { if (!dd.contains(e.target)) menu.classList.add("hidden"); });
  });
}

