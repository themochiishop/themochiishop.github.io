export const LANGS = [["en", "EN"], ["ms", "BM"], ["zh", "中文"]];

// 各语言的国旗图片与名称
const FLAGS = {
  en: { img: "https://flagcdn.com/gb.svg", name: "English" },
  ms: { img: "https://flagcdn.com/my.svg", name: "Bahasa Melayu" },
  zh: { img: "https://flagcdn.com/cn.svg", name: "中文" },
};
const flagImg = code => `<img class="flag" src="${FLAGS[code].img}" alt="" width="24" height="18">`;
const STORE_KEY = "mochii_lang";

function detectLang() {
  try {
    const saved = localStorage.getItem(STORE_KEY);
    if (saved && DICT[saved]) return saved;
  } catch (e) {}
  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("zh")) return "zh";
  if (nav.startsWith("ms") || nav.startsWith("id")) return "ms";
  return "en";
}

export const lang = detectLang();

export function setLang(l) {
  try { localStorage.setItem(STORE_KEY, l); } catch (e) {}
  location.reload();
}

// 取得翻译；{name} 这类占位会被替换
export function t(key, vars) {
  let s = DICT[lang][key];
  if (s === undefined) s = DICT.en[key];
  if (s === undefined) return key;
  if (vars) Object.keys(vars).forEach(k => { s = s.split("{" + k + "}").join(vars[k]); });
  return s;
}

// 把页面上 data-i18n 的元素换成当前语言
export function applyI18n(root = document) {
  document.documentElement.lang = lang === "zh" ? "zh-CN" : lang;
  root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-ph]").forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  const titleEl = document.querySelector("title[data-i18n-title]");
  if (titleEl) document.title = t(titleEl.dataset.i18nTitle);
}

// 语言切换按钮
export function langSwitchHTML() {
  const cur = LANGS.find(([c]) => c === lang) || LANGS[0];
  return `<div class="lang-dd">
    <button type="button" class="lang-btn" aria-haspopup="true" aria-label="${t("lang.choose")}" title="${FLAGS[cur[0]].name}">${flagImg(cur[0])}</button>    <div class="lang-menu hidden" role="menu">
      ${LANGS.map(([code, label]) =>
                `<button type="button" role="menuitem" data-setlang="${code}" class="${code === lang ? "active" : ""}">${flagImg(code)} ${FLAGS[code].name}</button>`).join("")}
    </div>
  </div>`;
}

// 语言按钮：平常只显示目前语言，点了才展开选单
export function bindLangSwitch(root = document) {
  root.querySelectorAll(".lang-dd").forEach(dd => {
    const btn = dd.querySelector(".lang-btn");
    const menu = dd.querySelector(".lang-menu");
    btn.addEventListener("click", e => { e.stopPropagation(); menu.classList.toggle("hidden"); });
    menu.querySelectorAll("[data-setlang]").forEach(b => {
      b.addEventListener("click", () => {
        menu.classList.add("hidden");
        if (b.dataset.setlang !== lang) setLang(b.dataset.setlang);
      });
    });
    document.addEventListener("click", e => { if (!dd.contains(e.target)) menu.classList.add("hidden"); });
  });
}

// ---------- 系统写入的积分原因（中文）→ 当前语言 ----------
const ZH_TIER = { "Mochii 会员": "mochii", "银卡": "silver", "金卡": "gold", "钻石": "diamond" };

function tierFromZh(label) {
  const id = ZH_TIER[label];
  return id ? t("tier." + id) : label;
}

export function translateReason(reason) {
  const r = String(reason || "");
  let m;
  if (r === "购物积分") return t("reason.purchase");
  if ((m = r.match(/^购物积分（(.+) ×([\d.]+)）$/))) return t("reason.purchaseTier", { tier: tierFromZh(m[1]), m: m[2] });
  if (r === "订单取消/退货") return t("reason.cancel");
  if (r === "订单金额更正") return t("reason.amend");
  if (r === "订单转出") return t("reason.transfer");
  if ((m = r.match(/^🎂 生日礼物（(.+)）$/))) return t("reason.birthday", { tier: tierFromZh(m[1]) });
  if (r.startsWith("奖励：")) return t("reason.bonus") + r.slice(3);
  if (r.startsWith("调整：")) return t("reason.adjust") + r.slice(3);
  if (r.startsWith("兑换：")) return t("reason.redeem") + r.slice(3);
  return r;
}
