const ZH_TIER = { "Mochii 会员": "mochii", "银卡": "silver", "金卡": "gold", "钻石": "diamond", "Black Elite": "black" };

function tierFromZh(label) {
  const id = ZH_TIER[label];
  return id ? t("tier." + id) : label;
}

export function translateReason(reason) {
  // 🎉 迎新礼的兑换 / 退回：后端写「（新会员礼）」，换成会员的语言
  const NM_SUFFIX = { zh: "（新会员礼）", en: " (new member gift)", ms: " (hadiah ahli baharu)" };
  const r = String(reason || "").replace("（新会员礼）", NM_SUFFIX[lang] || NM_SUFFIX.en);
  let m;
  if (r === "购物积分") return t("reason.purchase");
  if ((m = r.match(/^购物积分（(.+) ×([\d.]+)）$/))) return t("reason.purchaseTier", { tier: tierFromZh(m[1]), m: m[2] });
  if (r === "订单取消/退货") return t("reason.cancel");
  if (r === "订单金额更正") return t("reason.amend");
  if (r === "订单转出") return t("reason.transfer");
  if ((m = r.match(/^🎂 生日礼物（(.+)）$/))) return t("reason.birthday", { tier: tierFromZh(m[1]) });
  if (r.startsWith("奖励：")) return t("reason.bonus") + r.slice(3);
  if (r.startsWith("调整：")) return t("reason.adjust") + r.slice(3);
  if (r.startsWith("兑换取消退回：")) return t("reason.redeemRefund") + r.slice(7);
  if (r.startsWith("兑换：")) return t("reason.redeem") + r.slice(3);
  if (r === "新会员欢迎礼") return t("reason.welcome");
  if (r === "完善资料：生日") return t("reason.profileBirthday");
  if (r === "完善资料：WhatsApp 通知") return t("reason.profileWhatsapp");
  if (r === "完善资料：绑定第二个平台") return t("reason.profilePlatform2");
  if (r === "完善资料：上传头像") return t("reason.profileAvatar");
  if (r === "积分过期") return t("reason.expired");
  if (r.startsWith("关注我们：")) return t("reason.follow", { p: r.slice(5) });
  if ((m = r.match(/^每日签到：第(\d)天$/))) return t("reason.checkin", { n: m[1] });
  return r;
}
