export function ft(key, vars) {
  let s = (FD[lang] || FD.en)[key];
  if (s === undefined) s = FD.en[key];
  if (s === undefined) return key;
  if (vars) Object.keys(vars).forEach(k => { s = s.split("{" + k + "}").join(vars[k]); });
  return s;
}
